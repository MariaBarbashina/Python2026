# Лабораторная работа 5. Задание 2: палиндром (через срез [::-1])
# Правила: регистр и обычные пробелы " " игнорируются,
# остальные символы (в том числе пунктуация) сравниваются как есть.

text = input("Введите текст: ")

cleaned = text.lower().replace(" ", "")

if cleaned == "":
    print("Нет текста")
elif cleaned == cleaned[::-1]:
    print("Палиндром")
else:
    print("Не палиндром")
