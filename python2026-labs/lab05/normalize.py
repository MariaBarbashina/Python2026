# Лабораторная работа 5. Задание 1: нормализация текста
# Удаляем пробельные символы по краям, последовательности внутри заменяем
# одним пробелом. Регистр сохраняется.

text = input("Введите текст: ")

words = text.split()
normalized = " ".join(words)

print(f"Исходная длина: {len(text)}")
print(f"Новая длина: {len(normalized)}")
print(f"Нормализованный текст: '{normalized}'")
print(f"Количество слов: {len(words)}")
