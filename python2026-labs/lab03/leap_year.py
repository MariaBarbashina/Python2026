# Лабораторная работа 3. Дополнительное задание: високосный год
# Год високосный, если делится на 400 либо делится на 4, но не на 100.

year = int(input("Год (от 1 до 9999): "))

if year < 1 or year > 9999:
    print("Ошибка диапазона")
elif year % 400 == 0 or (year % 4 == 0 and year % 100 != 0):
    print(f"{year} — високосный: да")
else:
    print(f"{year} — високосный: нет")
