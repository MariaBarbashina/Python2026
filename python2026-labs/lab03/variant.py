# Лабораторная работа 3. Индивидуальный вариант 10: прогресс загрузки файла
# 0–4: Начало, 5–94: Загрузка, 95–100: Завершение.

progress = int(input("Прогресс загрузки файла, % (от 0 до 100): "))

if progress < 0 or progress > 100:
    print("Ошибка диапазона")
elif progress <= 4:
    print("Начало")
elif progress <= 94:
    print("Загрузка")
else:
    print("Завершение")
