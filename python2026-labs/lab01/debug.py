# Лабораторная работа 1. Задание 3: поиск и исправление ошибок

# ---------- Фрагмент А ----------
# Ожидалось: 5. Ошибка: "2" и "3" — строки (str), поэтому "+" соединяет
# их в "23", а не складывает.
# Исправление: преобразовать строки в целые числа через int().
first = "2"
second = "3"
print("Фрагмент А")
print("Типы до преобразования:", type(first), type(second))
first_number = int(first)
second_number = int(second)
print("Типы после преобразования:", type(first_number), type(second_number))
print("Сумма:", first_number + second_number)
print()

# ---------- Фрагмент Б ----------
# Ожидалось: при вводе 17 вывести 18. Ошибка: input() возвращает строку,
# а сложение строки и целого числа вызывает TypeError.
# Исправление: преобразовать введённую строку в int перед сложением.
print("Фрагмент Б")
age = input("Возраст: ")
print("Тип до преобразования:", type(age))
age_number = int(age)
print("Тип после преобразования:", type(age_number))
print("Возраст через год:", age_number + 1)
print()

# ---------- Фрагмент В ----------
# Ожидалось: 7.0. Ошибка: деление выполняется раньше сложения, поэтому
# вычислялось 4 + 7 + 10 / 3 = 14.333...
# Исправление: заключить сумму в скобки.
first = 4
