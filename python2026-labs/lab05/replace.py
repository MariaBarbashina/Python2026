# Лабораторная работа 5. Задание 3: замена двоеточий на дефисы с подсчётом

text = input("Введите текст: ")

# сначала считаем вхождения в исходном тексте, затем заменяем
replacements = text.count(":")
new_text = text.replace(":", "-")

print(f"Количество замен: {replacements}")
print(f"Новая строка: {new_text}")
